"""Interface themes. The choice is one setting (section "ui", name "theme") shared by every browser.

Classic is the base stylesheet; the other themes live in static/themes.css, generated by
scripts/build_themes.py and switched with <html data-theme="...">.
"""
from __future__ import annotations

import threading

DEFAULT_THEME = "classic"

# id -> (label, description). Order is the order shown in the picker.
THEMES = {
    "classic": ("Classic", "The standard TV Manager look."),
    "glassy": ("Glassy", "Frosted, translucent panels over a soft colour backdrop."),
    "midnight": ("Midnight", "Near-black neutral surfaces with the same accents."),
    "daylight": ("Daylight", "A light theme for bright rooms."),
}

_lock = threading.Lock()
_cached: str | None = None


def normalize(value) -> str:
    v = str(value or "").strip().lower()
    return v if v in THEMES else DEFAULT_THEME


def current() -> str:
    """The saved theme; Classic if none is saved or the database cannot be read."""
    global _cached
    if _cached is not None:
        return _cached
    try:
        import engine
        value = normalize(engine.get_setting("ui", "theme", DEFAULT_THEME))
    except Exception:
        return DEFAULT_THEME
    with _lock:
        _cached = value
    return value


def save(value) -> str:
    v = str(value or "").strip().lower()
    if v not in THEMES:
        raise ValueError(f"Unknown theme: {value!r}. Choose one of: {', '.join(THEMES)}.")
    import engine
    engine.set_setting("ui", "theme", v)
    global _cached
    with _lock:
        _cached = v
    return v


def catalog() -> list[dict]:
    return [{"id": k, "label": label, "description": desc} for k, (label, desc) in THEMES.items()]
